-- =====================================================================
--  006_bank_beneficiary_address.sql —— 银行转账「收款人地址」+ 完整收款信息
--
--  背景：SWIFT 汇款的报头里有两段地址，容易被填错位置 ——
--        ① 收款人地址（beneficiary address，收款公司自己的地址）
--        ② 银行地址（bank address，汇款路径上的银行地址）
--        原来只有 ②，缺 ①，部分境外银行/支付平台会因地址不匹配退回或挂起。
--        新增 bank_ben_addr 独立字段，两个地址各归各位，不再互相顶替。
--
--  ★ 幂等：INSERT IGNORE —— 只在该 key 不存在（或为空串）时写入，
--    绝不覆盖后台已经填好的值。宝塔里误跑两次安全。
--    在宝塔 → 数据库 → phpMyAdmin / SQL 里整体执行即可。
-- =====================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------
-- 账号格式说明
--   账号本体 16 位：0000000000000000
--   页面上显示为 4 位一组（8888 8883 3796 5204）便于客户核对，
--   但存进库的是无空格版 —— SWIFT field 32A 只吃数字，
--   带空格会被部分境外行拒收或截断。
--
-- 银行地址说明
--   原文的楼层范围用的是 EN DASH（–，U+2013），不在 SWIFT X 字符集内，
--   严格校验的境外行会截断整行地址。这里统一改为 ASCII 连字符（-）。
-- ---------------------------------------------------------------------

INSERT IGNORE INTO `settings` (`k`,`v`) VALUES
  ('bank_beneficiary', 'Example IP Agency Co., Ltd.'),
  ('bank_ben_addr',    '1 Example Road, Suite 100, Shanghai, China'),
  ('bank_name',        'BANK OF EXAMPLE, SHANGHAI.'),
  ('bank_account',     '0000000000000000'),
  ('bank_swift',       'EXAMPLE0XXX'),
  ('bank_addr',        '1 Example Road, Shanghai, China');

-- ---------------------------------------------------------------------
-- 执行后自检：应返回 6 行，且 bank_account 为 16 位纯数字
--   SELECT `k`, `v` FROM `settings` WHERE `k` LIKE 'bank_%' ORDER BY `k`;
-- ---------------------------------------------------------------------

-- ---------------------------------------------------------------------
-- 修正：把银行地址里的 EN DASH 换成 ASCII 连字符
--
-- 上面 INSERT IGNORE 只在该 key 不存在时才写。若后台已手工填过
-- bank_addr（填的是「Floors 14–20」带EN DASH，U+2013），这一行不会生效，
-- 页面上就还是en-dash —— 2026-10-14 客户实测页面上确实是en-dash。
--
-- 为什么必须换：SWIFT 报文 field 32B/33B（地址）按 X 字符集限制，
-- EN DASH 不在其中。严格校验的境外行会截断该字段或整笔退回，
-- 而地址是被要求必填的字段，退回＝客户的钱在路上卡住。
--
-- ★ 只替换 en-dash 这一个字符，不动地址里的其他内容（逗号、点、P.R.China 等
--   都在 X 字符集内，合法）。
--   WHERE 用 CHAR(0x2013) 精确匹配，避免误伤别的字符。
-- ---------------------------------------------------------------------
UPDATE `settings`
   SET `v` = REPLACE(`v`, CHAR(0x2013), '-')
 WHERE `k` = 'bank_addr'
   AND `v` LIKE CONCAT('%', CHAR(0x2013), '%');

